// Generates crates/waproto/src/generated.rs from upstream/WAProto/WAProto.proto. Plain Rust, no proc macros, so lust can compile it.
import { createRequire } from 'module'
import { readFileSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'
const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(join(here, '../upstream/package.json'))
const pb = require('protobufjs')
const root = pb.parse(readFileSync(join(here, '../upstream/WAProto/WAProto.proto'), 'utf8'), { keepCase: true }).root
root.resolveAll()

const KW = new Set('as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro override priv typeof unsized virtual yield try gen'.split(' '))
const id = s => (s === 'self' || s === 'Self' || s === 'crate' || s === 'super') ? s + '_' : KW.has(s) ? 'r#' + s : s
const snake = s => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z])([A-Z][a-z])/g, '$1_$2').toLowerCase()
const camelType = s => s.replace(/^[a-z]/, c => c.toUpperCase())
const pathOf = t => {
	const parts = []
	for (let p = t.parent; p && p.name; p = p.parent) if (p.name !== 'proto') parts.unshift(id(snake(p.name)))
	return ['crate', ...parts, id(camelType(t.name))].join('::')
}
const SCALAR = {
	double: ['f64', 1, 'double'], float: ['f32', 5, 'float'], int32: ['i32', 0, 'int32'], int64: ['i64', 0, 'int64'], uint32: ['u32', 0, 'uint32'], uint64: ['u64', 0, 'uint64'],
	sint32: ['i32', 0, 'sint32'], sint64: ['i64', 0, 'sint64'], fixed32: ['u32', 5, 'fixed32'], fixed64: ['u64', 1, 'fixed64'], sfixed32: ['i32', 5, 'sfixed32'], sfixed64: ['i64', 1, 'sfixed64'],
	bool: ['bool', 0, 'bool'], string: ['Str', 2, 'str'], bytes: ['Bytes', 2, 'bytes']
}
const tag = (n, w) => (n << 3) | w
const varintBytes = v => { const o = []; while (v > 127) { o.push((v & 127) | 128); v >>>= 7 } o.push(v); return o }

// Fields that Baileys adds to proto objects in JavaScript. They live on the message but never reach the wire or toJSON.
const LOCAL = {
	MessageKey: [['remoteJidAlt', 'string'], ['remoteJidUsername', 'string'], ['participantAlt', 'string'], ['participantUsername', 'string'], ['server_id', 'string'], ['addressingMode', 'string'], ['isViewOnce', 'bool']],
	WebMessageInfo: [['category', 'string'], ['retryCount', 'uint32']],
	Conversation: [['lastMessageRecvTimestamp', 'uint64'], ['timestamp', 'uint64']]
}
// Partial updates of these messages can hold an explicit null, which Object.assign copies over an old value.
const NULLABLE = new Set(['Conversation', 'WebMessageInfo'])
// `unreadCount: -1` marks a chat as unread in Baileys, so the Rust type must be signed. The wire stays uint32.
const SIGNED_UINT32 = { Conversation: new Set(['unreadCount']) }
SCALAR.uint32_i32 = ['i32', 0, 'uint32_i32']

let out = '// @generated by scripts/protogen.mjs. Do not edit.\n#![allow(non_snake_case, non_camel_case_types, unused_imports, clippy::all)]\nuse crate::pb::*;\n'

const emitEnum = (e, ind) => {
	const n = id(camelType(e.name))
	let s = `${ind}#[derive(Clone, Copy, PartialEq, Eq, Hash, Default, Debug, PartialOrd, Ord)]\n${ind}pub struct ${n}(pub i32);\n${ind}impl ${n} {\n`
	const seen = new Set(), byVal = new Map()
	for (const [k, v] of Object.entries(e.values)) {
		let name = id(k)
		if (seen.has(name)) continue
		seen.add(name)
		s += `${ind}    pub const ${name}: ${n} = ${n}(${v});\n`
		if (!byVal.has(v)) byVal.set(v, k)
	}
	s += `${ind}    pub fn name(self) -> Opt<&'static str> { match self.0 { ${[...byVal].map(([v, k]) => `${v} => Some(${JSON.stringify(k)})`).join(', ')}, _ => None } }\n`
	s += `${ind}    pub fn from_name(s: &str) -> Opt<${n}> { match s { ${Object.entries(e.values).map(([k, v]) => `${JSON.stringify(k)} => Some(${n}(${v}))`).join(', ')}, _ => None } }\n`
	s += `${ind}}\n`
	s += `${ind}impl From<i32> for ${n} { fn from(v: i32) -> ${n} { ${n}(v) } }\n`
	s += `${ind}impl From<${n}> for crate::pb::i32Wrap { fn from(v: ${n}) -> crate::pb::i32Wrap { crate::pb::i32Wrap(v.0) } }\n`
	return s
}

const emitMsg = (m, ind) => {
	const n = id(camelType(m.name))
	const en = n.replace(/^r#/, '') + 'Field'
	const topLevel = m.parent && m.parent.name === 'proto'
	const fields = m.fieldsArray.slice().sort((a, b) => a.id - b.id)
	for (const f of fields) { f.resolve(); if (topLevel && SIGNED_UINT32[m.name]?.has(f.name)) f.type = 'uint32_i32' }
	if (topLevel) for (const [i, [name, type]] of (LOCAL[m.name] || []).entries()) fields.push({ name, type, id: 1001 + i, local: true })
	const nullable = topLevel && NULLABLE.has(m.name)
	const rname = f => snake(f.name)
	const fnName = (pre, f, post = '') => {
		const raw = pre + rname(f) + post
		return (raw === 'self' || raw === 'Self' || raw === 'crate' || raw === 'super') ? raw + '_' : KW.has(raw) ? 'r#' + raw : raw
	}
	const isMsg = f => f.resolvedType && !(f.resolvedType instanceof pb.Enum)
	const isEnum = f => f.resolvedType instanceof pb.Enum
	const elem = f => f.resolvedType ? pathOf(f.resolvedType) : SCALAR[f.type][0]
	const ty = f => f.map ? `Vec<(${SCALAR[f.keyType][0]}, ${elem(f)})>` : f.repeated ? `Vec<${elem(f)}>` : elem(f)
	const isCopy = f => !f.repeated && !f.map && !isMsg(f) && (isEnum(f) || !['Str', 'Bytes'].includes(SCALAR[f.type][0]))
	const names = new Set()
	for (const f of fields) { const r = rname(f); if (names.has(r)) throw new Error('dup field ' + m.name + '.' + r); names.add(r) }
	let s = `${ind}/// Holds only the fields that are set, sorted by field number.\n${ind}#[derive(Clone, Default, PartialEq, Debug)]\n${ind}pub struct ${n}(Vec<${en}>);\n`
	s += `${ind}/// The discriminant is the field number, so \`no\` costs one load.\n${ind}#[derive(Clone, PartialEq, Debug)]\n${ind}#[repr(u32)]\n${ind}pub enum ${en} {\n`
	for (const f of fields) s += `${ind}    F${f.id}(${ty(f)}) = ${f.id},\n`
	if (nullable) s += `${ind}    /// An explicit null for the field with this number.\n${ind}    Null(u32) = 0x7fffffff,\n`
	s += `${ind}    #[doc(hidden)]\n${ind}    None = 0,\n${ind}}\n`
	const nullArm = nullable ? `${en}::Null(n) => *n, ` : ''
	const skipNull = nullable ? `${ind}                ${en}::Null(_) => {}\n` : ''
	s += `${ind}impl ${en} {\n${ind}    #[inline]\n${ind}    fn no(&self) -> u32 { match self { ${fields.map(f => `${en}::F${f.id}(_) => ${f.id}`).join(', ')}${fields.length ? ', ' : ''}${nullArm}${en}::None => 0 } }\n`
	s += `${ind}    fn name(&self) -> &'static str { match self { ${fields.map(f => `${en}::F${f.id}(_) => ${JSON.stringify(f.name)}`).join(', ')}${fields.length ? ', ' : ''}_ => "" } }\n${ind}}\n`
	s += `${ind}impl ${n} {\n${ind}    pub fn new() -> Self { <Self as Default>::default() }\n`
	s += `${ind}    #[inline]\n${ind}    fn pos(&self, no: u32) -> Result<usize, usize> { if let Some(l) = self.0.last() { if l.no() < no { return Err(self.0.len()); } } self.0.binary_search_by_key(&no, ${en}::no) }\n`
	s += `${ind}    #[inline]\n${ind}    fn put(&mut self, no: u32, v: ${en}) { match self.pos(no) { Ok(i) => self.0[i] = v, Err(i) => self.0.insert(i, v) } }\n`
	s += `${ind}    /// Same as \`Object.assign(self, o)\`: each field set in \`o\` replaces the field here.\n${ind}    pub fn assign_from(&mut self, o: &Self) { for f in &o.0 { self.put(f.no(), f.clone()); } }\n`
	s += `${ind}    /// Names of the fields that are set, in field number order.\n${ind}    pub fn set_field_names(&self) -> impl Iterator<Item = &'static str> + '_ { self.0.iter().map(${en}::name).filter(|n| !n.is_empty()) }\n`
	for (const f of fields) {
		const t = ty(f)
		const V = `${en}::F${f.id}`
		const get = fnName('', f), set = fnName('set_', f), wth = fnName('with_', f), mt = fnName('', f, '_mut'), clr = fnName('clear_', f)
		if (f.map || f.repeated) {
			s += `${ind}    pub fn ${get}(&self) -> &[${f.map ? `(${SCALAR[f.keyType][0]}, ${elem(f)})` : elem(f)}] { match self.pos(${f.id}) { Ok(i) => match &self.0[i] { ${V}(v) => v, _ => &[] }, _ => &[] } }\n`
		} else if (isCopy(f)) {
			s += `${ind}    pub fn ${get}(&self) -> Opt<${t}> { match self.pos(${f.id}) { Ok(i) => match &self.0[i] { ${V}(v) => Some(*v), _ => None }, _ => None } }\n`
		} else {
			s += `${ind}    pub fn ${get}(&self) -> Opt<&${t}> { match self.pos(${f.id}) { Ok(i) => match &self.0[i] { ${V}(v) => Some(v), _ => None }, _ => None } }\n`
		}
		s += `${ind}    pub fn ${set}(&mut self, v: impl Into<${t}>) { self.put(${f.id}, ${V}(v.into())) }\n`
		s += `${ind}    pub fn ${wth}(mut self, v: impl Into<${t}>) -> Self { self.put(${f.id}, ${V}(v.into())); self }\n`
		s += `${ind}    pub fn ${clr}(&mut self) { if let Ok(i) = self.pos(${f.id}) { self.0.remove(i); } }\n`
		if (!isCopy(f)) {
			const dflt = '<' + t + ' as Default>::default()'
			const onHit = nullable ? `Ok(i) => { if matches!(self.0[i], ${en}::Null(_)) { self.0[i] = ${V}(${dflt}); } i }` : 'Ok(i) => i'
			s += `${ind}    /// Sets the field to its default first when it is not set.\n${ind}    pub fn ${mt}(&mut self) -> &mut ${t} { let i = match self.pos(${f.id}) { ${onHit}, Err(i) => { self.0.insert(i, ${V}(${dflt})); i } }; match &mut self.0[i] { ${V}(v) => v, _ => unreachable!() } }\n`
		}
		if (nullable && !f.local) {
			s += `${ind}    /// Same as \`${f.name}: null\` in a JavaScript object.\n${ind}    pub fn ${fnName('set_', f, '_null')}(&mut self) { self.put(${f.id}, ${en}::Null(${f.id})) }\n`
			s += `${ind}    pub fn ${fnName('', f, '_is_null')}(&self) -> bool { match self.pos(${f.id}) { Ok(i) => matches!(self.0[i], ${en}::Null(_)), _ => false } }\n`
		}
	}
	s += `${ind}}\n${ind}impl PbMessage for ${n} {\n`
	s += `${ind}    fn encode_to(&self, w: &mut Writer) {\n${ind}        for f in &self.0 {\n${ind}            match f {\n`
	const tagB = (f, wt) => `w.tag(&[${varintBytes(tag(f.id, wt)).join(',')}]);`
	for (const f of fields) {
		const V = `${en}::F${f.id}`
		if (f.local) { s += `${ind}                ${V}(_) => {}\n`; continue }
		if (f.map) {
			const putV = isMsg(f) ? 'w.tag(&[18]); w.nested(v);' : `w.tag(&[${varintBytes(tag(2, SCALAR[f.type][1])).join(',')}]); w.${SCALAR[f.type][2]}(${['Str', 'Bytes'].includes(SCALAR[f.type][0]) ? 'v' : '*v'});`
			s += `${ind}                ${V}(a) => { for (k, v) in a { ${tagB(f, 2)} let st = w.begin(); w.tag(&[${varintBytes(tag(1, SCALAR[f.keyType][1])).join(',')}]); w.${SCALAR[f.keyType][2]}(${SCALAR[f.keyType][0] === 'Str' ? 'k' : '*k'}); ${putV} w.end(st); } }\n`
		} else if (isMsg(f)) {
			if (f.repeated) s += `${ind}                ${V}(a) => { for v in a { ${tagB(f, 2)} w.nested(v); } }\n`
			else s += `${ind}                ${V}(v) => { ${tagB(f, 2)} w.nested(v); }\n`
		} else {
			const [wname, wt, meth] = isEnum(f) ? ['i32', 0, 'int32'] : SCALAR[f.type]
			const val = isEnum(f) ? 'v.0' : (wname === 'Str' || wname === 'Bytes') ? 'v' : '*v'
			if (f.repeated) {
				if (wt !== 2) s += `${ind}                ${V}(a) => { if !a.is_empty() { ${tagB(f, 2)} let st = w.begin(); for v in a { w.${meth}(${val}); } w.end(st); } }\n`
				else s += `${ind}                ${V}(a) => { for v in a { ${tagB(f, wt)} w.${meth}(${val}); } }\n`
			} else s += `${ind}                ${V}(v) => { ${tagB(f, wt)} w.${meth}(${val}); }\n`
		}
	}
	s += skipNull + `${ind}                ${en}::None => {}\n${ind}            }\n${ind}        }\n${ind}    }\n`
	s += `${ind}    fn merge_from(&mut self, r: &mut Reader<'_>) -> Result<(), DecodeError> {\n${ind}        self.0.reserve_exact(r.count_fields());\n${ind}        while let Some((field, wt)) = r.next_field()? {\n${ind}            match field {\n`
	for (const f of fields.filter(f => !f.local)) {
		const V = `${en}::F${f.id}`
		const mt = fnName('', f, '_mut')
		const t = elem(f)
		if (f.map) {
			s += `${ind}                ${f.id} => { let e = r.begin_packed()?; let mut k = Default::default(); let mut v = <${t}>::default(); while r.pos_before(e) { let Some((nf, nw)) = r.next_field_until(e)? else { break }; match nf { 1 => k = r.${SCALAR[f.keyType][2]}()?, 2 => v = ${isMsg(f) ? `r.message::<${t}>()?` : `r.${SCALAR[f.type][2]}()?`}, _ => r.skip(nw)? } } self.${mt}().push((k, v)); }\n`
		} else if (isMsg(f)) {
			if (f.repeated) s += `${ind}                ${f.id} => { let v = r.message::<${t}>()?; self.${mt}().push(v); }\n`
			else s += `${ind}                ${f.id} => { let v = r.message::<${t}>()?; self.put(${f.id}, ${V}(v)); }\n`
		} else {
			const [wname, wt, meth] = isEnum(f) ? ['i32', 0, 'int32'] : SCALAR[f.type]
			const dec = isEnum(f) ? `${t}(r.int32()?)` : `r.${meth}()?`
			if (f.repeated) {
				if (wt !== 2) s += `${ind}                ${f.id} => { if wt == 2 { let e = r.begin_packed()?; while r.pos_before(e) { let v = ${dec}; self.${mt}().push(v); } } else { let v = ${dec}; self.${mt}().push(v); } }\n`
				else s += `${ind}                ${f.id} => { let v = ${dec}; self.${mt}().push(v); }\n`
			} else s += `${ind}                ${f.id} => { let v = ${dec}; self.put(${f.id}, ${V}(v)); }\n`
		}
	}
	s += `${ind}                _ => r.skip(wt)?,\n${ind}            }\n${ind}        }\n${ind}        Ok(())\n${ind}    }\n`
	const js = (f, v) => {
		if (isMsg(f)) return `${v}.to_json()`
		if (isEnum(f)) return `enum_json(${v}.name(), ${v}.0)`
		const w = SCALAR[f.type][0]
		if (w === 'Str') return `Json::Str(${v}.as_str().to_string())`
		if (w === 'Bytes') return `Json::Str(base64_encode(${v}.as_slice()))`
		if (w === 'i64' || w === 'u64') return `Json::Str(${v}.to_string())`
		if (w === 'bool') return `Json::Bool(*${v})`
		if (w === 'f32' || w === 'f64') return `float_json(*${v} as f64)`
		return `Json::Num(*${v} as f64)`
	}
	s += `${ind}    fn to_json(&self) -> Json {\n${ind}        let mut o: Vec<(String, Json)> = Vec::with_capacity(self.0.len());\n${ind}        for f in &self.0 {\n${ind}            match f {\n`
	for (const f of fields) {
		const V = `${en}::F${f.id}`, nm = JSON.stringify(f.name)
		if (f.local) s += `${ind}                ${V}(_) => {}\n`
		else if (f.map) s += `${ind}                ${V}(a) => o.push((${nm}.to_string(), Json::Obj(a.iter().map(|(k, v)| (k.to_string(), ${js(f, 'v')})).collect()))),\n`
		else if (f.repeated) s += `${ind}                ${V}(a) => o.push((${nm}.to_string(), Json::Arr(a.iter().map(|v| ${js(f, 'v')}).collect()))),\n`
		else s += `${ind}                ${V}(v) => o.push((${nm}.to_string(), ${js(f, 'v')})),\n`
	}
	s += skipNull + `${ind}                ${en}::None => {}\n${ind}            }\n${ind}        }\n${ind}        Json::Obj(o)\n${ind}    }\n`
	const fj = (f, v) => {
		if (isMsg(f)) return `<${elem(f)} as PbMessage>::from_json(${v})?`
		if (isEnum(f)) return `${elem(f)}(enum_from_json(${v}, ${elem(f)}::from_name)?)`
		const w = SCALAR[f.type][0]
		if (f.type === 'uint32_i32') return `i64_from_json(${v})? as i32`
		return ({ Str: `str_from_json(${v})?`, Bytes: `bytes_from_json(${v})?`, i64: `i64_from_json(${v})?`, u64: `u64_from_json(${v})?`, bool: `bool_from_json(${v})?`, f32: `f64_from_json(${v})? as f32`, f64: `f64_from_json(${v})?`, i32: `i64_from_json(${v})? as i32`, u32: `i64_from_json(${v})? as u32` })[w]
	}
	s += `${ind}    fn from_json(j: &Json) -> Result<Self, DecodeError> {\n${ind}        let mut m = <Self as Default>::default();\n${ind}        let Json::Obj(o) = j else { return Err(DecodeError::new("object expected")); };\n${ind}        for (k, v) in o {\n${ind}            if matches!(v, Json::Null) { continue; }\n${ind}            match k.as_str() {\n`
	for (const f of fields.filter(f => !f.local)) {
		const V = `${en}::F${f.id}`, nm = JSON.stringify(f.name), mt = fnName('', f, '_mut')
		if (f.map) s += `${ind}                ${nm} => { let Json::Obj(a) = v else { return Err(DecodeError::new("object expected")); }; for (mk, x) in a { let e = (map_key_from_json(mk)?, ${fj(f, 'x')}); m.${mt}().push(e); } }\n`
		else if (f.repeated) s += `${ind}                ${nm} => { let Json::Arr(a) = v else { return Err(DecodeError::new("array expected")); }; for x in a { let e = ${fj(f, 'x')}; m.${mt}().push(e); } }\n`
		else s += `${ind}                ${nm} => { let e = ${fj(f, 'v')}; m.put(${f.id}, ${V}(e)); }\n`
	}
	s += `${ind}                _ => {}\n${ind}            }\n${ind}        }\n${ind}        Ok(m)\n${ind}    }\n${ind}}\n`
	const kids = (m.nestedArray || [])
	if (kids.length) {
		s += `${ind}pub mod ${id(snake(m.name))} {\n${ind}    use crate::pb::*;\n`
		for (const k of kids) s += k instanceof pb.Enum ? emitEnum(k, ind + '    ') : emitMsg(k, ind + '    ')
		s += `${ind}}\n`
	}
	return s
}

const ns = root.lookup('proto')
for (const k of ns.nestedArray) out += k instanceof pb.Enum ? emitEnum(k, '') : emitMsg(k, '')
out = out.replace(/crate::/g, 'crate::generated::').replace(/crate::generated::pb::/g, 'crate::pb::')
writeFileSync(join(here, '../crates/waproto/src/generated.rs'), out)
console.log('messages', out.match(/impl PbMessage for/g).length, 'lines', out.split('\n').length, 'bytes', out.length)
