// Generates crates/baileys/src/wabinary/tokens.rs from the built Baileys token tables.
import { writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'
const here = dirname(fileURLToPath(import.meta.url))
const c = await import(join(here, '../upstream/lib/WABinary/constants.js'))
const lit = s => JSON.stringify(s)
let o = '// @generated by scripts/tokengen.mjs. Do not edit.\n'
o += `pub const SINGLE_BYTE_TOKENS: &[&str] = &[${c.SINGLE_BYTE_TOKENS.map(lit).join(', ')}];\n`
o += `pub const DOUBLE_BYTE_TOKENS: &[&[&str]] = &[\n${c.DOUBLE_BYTE_TOKENS.map(d => '    &[' + d.map(lit).join(', ') + '],').join('\n')}\n];\n`
writeFileSync(join(here, '../crates/baileys/src/wabinary/tokens.rs'), o)
