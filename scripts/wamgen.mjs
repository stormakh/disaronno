// Generates crates/baileys/src/wam/constants.rs from the built Baileys WAM tables.
// The tables are text, read only when an event is encoded. Rust tables of pointers would need a
// relocation for each string at the start of every process, which costs resident memory for nothing.
import { writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'
const here = dirname(fileURLToPath(import.meta.url))
const c = await import(join(here, '../upstream/lib/WAM/constants.js'))
const safe = s => {
	if (/[\t\n|,=#"]/.test(String(s))) throw new Error(`a separator in ${s}`)
	return s
}
const ty = t => {
	if (typeof t !== 'string') return 'e' + Object.entries(t).map(([k, v]) => `,${safe(k)}=${v}`).join('')
	return { integer: 'i', boolean: 'b', string: 's', timer: 't', number: 'n' }[t]
}
const ev = e => [safe(e.name), e.id, e.weight, safe(e.wamChannel), e.privateStatsIdInt ?? '', ...Object.entries(e.props).map(([k, [id, t]]) => `${safe(k)}|${id}|${ty(t)}`)].join('\t')
const gl = g => [safe(g.name), g.id, ty(g.type), safe(g.validator ?? ''), g.channels.map(safe).join(',')].join('\t')
let o = '// @generated by scripts/wamgen.mjs. Do not edit.\n'
o += `pub const FLAG_BYTE: u8 = ${c.FLAG_BYTE};\npub const FLAG_GLOBAL: u8 = ${c.FLAG_GLOBAL};\npub const FLAG_EVENT: u8 = ${c.FLAG_EVENT};\npub const FLAG_FIELD: u8 = ${c.FLAG_FIELD};\npub const FLAG_EXTENDED: u8 = ${c.FLAG_EXTENDED};\n`
o += '/// One event per line, with tabs: name, id, weight, channel, private stats id, then `prop|id|type`.\n'
o += `pub const WEB_EVENTS_TEXT: &str = r#"${c.WEB_EVENTS.map(ev).join('\n')}"#;\n`
o += '/// One global per line, with tabs: name, id, type, validator, channels.\n'
o += `pub const WEB_GLOBALS_TEXT: &str = r#"${c.WEB_GLOBALS.map(gl).join('\n')}"#;\n`
writeFileSync(join(here, '../crates/baileys/src/wam/constants.rs'), o)
